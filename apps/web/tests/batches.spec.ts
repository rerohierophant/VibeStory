import { test, expect } from '@playwright/test';
import { prepareReferences } from './reference-fixture';

test('episode batches finish image and video tasks inline and restore their progress after reload', async ({ page, context, baseURL }) => {
  await context.route('**/*', route => route.request().url().startsWith(baseURL + '/') || /^(data|blob):/.test(route.request().url()) ? route.continue() : route.abort());
  await page.goto('/login');
  await page.getByLabel('邮箱', { exact: true }).fill(process.env.WEB_TEST_EMAIL!);
  await page.getByLabel('密码', { exact: true }).fill(process.env.WEB_TEST_PASSWORD!);
  await page.getByRole('button', { name: '进入工作台' }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.getByRole('button', { name: '新建项目', exact: true }).first().click();
  await page.getByPlaceholder('例如：长夜将明').fill('批次页面验收');
  await page.getByRole('button', { name: '创建项目', exact: true }).click();
  await expect(page).toHaveURL(/\/projects\/\d+$/);
  const projectPath = new URL(page.url()).pathname;
  const csrf = await (await page.request.get('/api/auth/csrf')).json();
  const created = await page.request.post(`/api${projectPath}/episodes`, {
    headers: { [csrf.headerName]: csrf.token }, data: {},
  });
  expect(created.status()).toBe(201);
  const { id } = await created.json();
  await page.goto(`${projectPath}/episodes/${id}/story`);
  await page.getByPlaceholder(/把这一集的剧本贴在这里/).fill('雨夜街道，沈夜收起伞走向便利店。店员抬起头，窗外的路灯映着积水。\n\n许星遥放下牛奶，低声说：「你终于回来了。」沈夜看着玻璃窗上的雨水。');
  await page.getByRole('button', { name: 'AI 拆解镜头', exact: true }).click();
  await page.getByRole('link', { name: '分镜', exact: true }).click();
  await expect(page.locator('tbody tr').first()).toBeVisible();
  await prepareReferences(page, projectPath.split('/')[2]);
  await page.reload();
  await page.getByRole('button', { name: '本集批量生成分镜图', exact: true }).click();
  let dialog = page.getByRole('dialog', { name: '本集批量生成分镜图' });
  const images = page.getByRole('region', { name: '分镜图批次进度' });
  await dialog.getByRole('button', { name: '选择本集镜头（最多 200）' }).click();
  await dialog.getByRole('button', { name: /^提交 \d+ 镜$/ }).click();
  await expect(dialog).toHaveCount(0);
  await expect(images.getByText('镜头 2 · 已接收 · 已生成')).toBeVisible();
  await expect(images.getByText('镜头 1 · 已接收 · 已生成')).toBeVisible();
  const batchId = (await images.getByText(/批次 #/).innerText()).match(/#(\d+)/)![1];
  await page.reload();
  await expect(images.getByText(`批次 #${batchId} · 已结束`)).toBeVisible();
  await images.getByRole('button', { name: '查看明细' }).click();
  await expect(images.getByText('镜头 1 · 已接收 · 已生成')).toBeVisible();
  await images.getByRole('button', { name: '收起明细' }).click();
  const firstShot = page.locator('tbody tr').first();
  await firstShot.getByRole('button', { name: '确认画面', exact: true }).click();
  await expect(firstShot.getByText('已确认', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: '视频', exact: true }).click();
  await page.getByRole('button', { name: '本集批量生成视频', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '本集批量生成视频' });
  await dialog.getByRole('button', { name: '提交 1 镜', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('region', { name: '视频批次进度' }).getByText('镜头 1 · 已接收 · 已生成')).toBeVisible();
  await page.reload();
  await expect(page.locator('article').first().getByLabel('镜头视频', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('vibestory.state.v2'))).toBeNull();
});
