CREATE TABLE shot_edit_proposal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id BIGINT NOT NULL,
    shot_id BIGINT NOT NULL,
    request_key UUID NOT NULL,
    instruction TEXT NOT NULL,
    base_version BIGINT NOT NULL,
    old_shot_size TEXT NOT NULL,
    new_shot_size TEXT,
    old_dialogue TEXT NOT NULL,
    new_dialogue TEXT,
    state VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING', 'APPLIED', 'DISCARDED')),
    FOREIGN KEY (shot_id, episode_id) REFERENCES shot(id, episode_id) ON DELETE CASCADE,
    UNIQUE (episode_id, request_key),
    CHECK (new_shot_size IS NOT NULL OR new_dialogue IS NOT NULL)
);

CREATE INDEX ix_shot_edit_proposal_latest ON shot_edit_proposal(episode_id, id DESC);
CREATE INDEX ix_shot_edit_proposal_shot ON shot_edit_proposal(shot_id);
