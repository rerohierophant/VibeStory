CREATE TABLE agent_conversation (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX ix_agent_conversation_history ON agent_conversation(user_id, updated_at DESC, id);

CREATE TABLE agent_chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES agent_conversation(id) ON DELETE CASCADE,
    request_key UUID NOT NULL,
    instruction TEXT NOT NULL,
    project_id BIGINT,
    episode_id BIGINT,
    result JSONB,
    error TEXT,
    UNIQUE (conversation_id, request_key)
);
CREATE INDEX ix_agent_chat_transcript ON agent_chat_message(conversation_id, id);

CREATE TABLE agent_chat_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES agent_chat_message(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    media_type VARCHAR(16) NOT NULL CHECK (media_type IN ('image/jpeg', 'image/png')),
    content BYTEA NOT NULL
);
CREATE INDEX ix_agent_chat_images ON agent_chat_image(message_id, id);
